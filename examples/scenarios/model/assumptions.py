"""Scenario assumptions: annual customer growth and net dollar retention by size group.

Each ramp is a tuple of (year, rate) steps. A step's rate applies through Dec 31 of
that year; the final step's rate extends indefinitely. Rates are percentages so they
render legibly in statement output (7.5 == 7.5% YoY growth, 114.0 == 114% NDR).
"""

from datetime import date

from orcaset import SpanSeriesDef, last_span, span, split_const

SCENARIOS = ("downside", "base", "upside")

type Ramp = tuple[tuple[int, float], ...]


def ramp_series(steps: Ramp, label: str) -> SpanSeriesDef:
    """Convert (year, rate) steps into a queryable, renderable assumption series."""
    records: list[tuple[tuple[date, date], float | None]] = []
    start = date.min
    for year, rate in steps[:-1]:
        end = date(year, 12, 31)
        records.append(((start, end), rate))
        start = end
    records.append(((start, date.max), steps[-1][1]))
    return span.from_list(records, agg=last_span(None), split=split_const, label=label)


